        '×' to "....... ....... ##...## .##.##. ..###.. .##.##. ##...## ....... .......",
    ).mapValues { (_, rows) -> rows.split(' ') }

    fun rows(c: Char): List<String>? = glyphs[c.uppercaseChar()]

    /** How wide [text] is in game pixels at one dot a pixel. */
    fun cells(text: String): Int {
        var n = 0
        for (ch in text) n += if (ch == ' ') SPACE else ADV
        return if (n == 0) 0 else n - 1
    }

    /** Empty columns on the left of [ch]. */
    private fun lead(ch: Char): Int = rows(ch)?.let { r -> (0 until W).firstOrNull { i -> r.any { it[i] == '#' } } } ?: 0

    /** Empty columns on the right of [ch]: a "!" sits at the left of its cell, so a line ending in one needs this. */
    private fun trail(ch: Char): Int = rows(ch)?.let { r -> (0 until W).firstOrNull { i -> r.any { it[W - 1 - i] == '#' } } } ?: 0

    /** Where [text] starts so that its ink, not its letter cells, sits in the middle of [cx]. */
    fun left(text: String, cx: Int, dot: Int = 1): Int {
        if (text.isEmpty()) return cx
        val l = lead(text.first()) * dot
        val r = cells(text) * dot - trail(text.last()) * dot
        return cx - (l + r) / 2
    }
}

