    /** One snail's parts. */
    private class Who(
        val top: ArtRows, val feelers: ArtRows, val face: ArtRows? = null, val under: ArtRows? = null,
        val extra: ArtRows? = null, val extraX: Int = 0, val extraY: Int = 0,
        val eyes: ArtRows = EYES, val shut: ArtRows = EYES_CLOSED, val glasses: Boolean = false,
        /** What's left in the air when its owner ducks into the shell. */
        val left: ArtRows? = top,
        /** Black hat, black shell, black clothes. */
        val outlaw: Boolean = false,
        /** What an outlaw wears over the black: white touches laid on the body, a neckerchief or a bullet belt. */
        val outfit: ArtRows? = null,
    )

    private fun build(w: Who, eyes: ArtRows = w.eyes, mouth: ArtRows? = w.face, eyesY: Int = 10, bare: Boolean = false): ArtRows {
        var p = ArtRows(List(40) { "" })
        // Outlaws are dressed in black ('T' is the cloth colour: black on them, white on good folk), with something
        // western in white over it: a spotted neckerchief and shirt buttons, a vest's shirt front, crossed bullet belts.
        // Good folk are dressed too, in white with the lines drawn on: a vest and a star, a shawl, overalls, an apron.
        val body = (if (bare) BODY_BARE else BODY).let { b ->
            if (w.outlaw) dress(b.swap('o', 'T'), w.outfit, 'T') else dress(b, w.outfit, 'o')
        }
        p = if (bare) p.with(body, 0, 20) else p.with(body, 0, 20).with(if (w.outlaw) SHELL_DARK else SHELL, 0, 25)
        p = p.with(HEAD, 0, 10)
        p = if (w.glasses) p.with(GLASSES, FACE_X, 11) else p.with(eyes, FACE_X, eyesY)
        p = p.with(mouth, FACE_X, 10)
        p = p.with(w.feelers, 0, 0).with(w.top, 0, 0)
        p = p.with(w.under, 0, 17)
        p = p.with(w.extra, w.extraX, w.extraY)
        return p
    }

    /** Lays [outfit] on a body, only where there's [cloth] to lay it on, so nothing strays outside the outline. */
    private fun dress(body: ArtRows, outfit: ArtRows?, cloth: Char): ArtRows {
        if (outfit == null) return body
        return ArtRows(body.rows.mapIndexed { j, r ->
            String(CharArray(r.length) { i -> outfit.at(i, j).takeIf { it != '.' && r[i] == cloth } ?: r[i] })
        })
    }

