    /** How far left of him his arms reach: his pictures are this much wider than he is. */
    private const val REACH = 10

    /**
     * Him at the keys, as you see someone at a piano from the side: his near arm lies across his chest from a round
     * shoulder out to a hand on the keys, so it's plainly his; of his far arm you see what shows past the near one, a
     * hand a little further along the keys and the forearm rising to it. The hands lift by turns ([frame]). With
     * [arms] false he's just sitting.
     */
    private fun pianistAt(frame: Int, arms: Boolean = true): ArtRows {
        val g = Array(PIANIST.h) { CharArray(PIANIST.w + REACH) { '.' } }
        PIANIST.rows.forEachIndexed { j, r -> r.forEachIndexed { i, c -> if (c != '.') g[j][i + REACH] = c } }
        if (!arms) return ArtRows(g.map { String(it) })
        val nearUp = frame % 2 == 1
        /** A hand: a mitt four pixels square at ([hx], [hy]), lined above, below and at its tip. */
        fun hand(hx: Int, hy: Int, set: (Int, Int, Char) -> Unit) {
            for (y in hy - 1..hy + 2) { for (x in hx..hx + 3) set(x, y, 'o'); set(hx - 1, y, '#') }
            for (x in hx..hx + 3) { set(x, hy - 2, '#'); set(x, hy + 3, '#') }
        }

        // The near arm, over him: two pixels thick with a line each side, closed with a round shoulder on his chest.
        val over = { x: Int, y: Int, c: Char -> g[y][x] = c }
        val sx = REACH + 11; val sy = 25
        val nx = 5; val ny = if (nearUp) 25 else 27
        for (t in 0..sx - nx - 4) {
            val x = sx - t; val y = sy + Math.round((ny - sy) * t / (sx - nx - 4f))
            over(x, y - 1, '#'); over(x, y, 'o'); over(x, y + 1, 'o'); over(x, y + 2, '#')
        }
        over(sx + 1, sy, '#'); over(sx + 1, sy + 1, '#')
        hand(nx, ny, over)

        // The far arm, behind everything: only what shows past the near one is drawn.
        val behind = { x: Int, y: Int, c: Char -> if (g[y][x] == '.') g[y][x] = c }
        val ex = REACH + 4; val ey = 26
        val fx = 1; val fy = if (nearUp) 24 else 22
        for (t in 0..ex - fx - 4) {
            val x = ex - t; val y = ey + Math.round((fy - ey) * t / (ex - fx - 4f))
            behind(x, y - 1, '#')
            for (yy in y..y + 3) { if (g[yy][x] != '.') break; g[yy][x] = 'o' }
        }
        hand(fx, fy, behind)
        return ArtRows(g.map { String(it) })
    }

