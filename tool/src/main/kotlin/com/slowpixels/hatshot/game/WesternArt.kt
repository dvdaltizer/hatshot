    /** A hit: the snail is inside its shell before the hat knows it, so the hat hangs there a moment. */
    private fun hidden(w: Who, hat: Boolean = true): ArtRows = ArtRows(List(40) { "" })
        .with(HIDING, 0, 22).with(if (w.outlaw) SHELL_DARK else SHELL, 0, 25)
        .let { if (hat) it.with(w.left, 0, 0).with(SPIN, 6, 12) else it }

    /**
     * What flies off when [name] is hit (a hat, or Belle's bow), as a picture the size of the whole snail so it can be
     * drawn where the snail is; null for those with nothing on their heads. On the Light Phone the hat doesn't hang in
     * the window: it hangs a moment, then goes up, turning over, and falls.
     */
    fun hatOf(name: String): Sprite? {
