    /**
     * [who] behind bars, in a dark opening [w] by [h] with her picture's corner at ([dx], [dy]) in it. She's cut out
     * of paper as ever; then the bars go over her, two pixels thick, at each of [bars] across from row [from] down to
     * [to], with a rail the same at each of [rails] down. A bar is the page's ink where it crosses the dark and black
     * where it crosses her, so it's seen to be one bar, in front of her, from the dark above her head on down. Her
     * eyes show between the bars: they're spaced for that.
     */
    fun behindBars(who: Sprite, w: Int, h: Int, dx: Int, dy: Int, bars: IntArray, from: Int = 0, to: Int = h,
                   rails: IntArray = IntArray(0)): Sprite {
        val c = who.cutout
        val px = IntArray(w * h) { PAGE }
        for (y in 0 until h) for (x in 0 until w) {
            val cx = x - dx + Sprite.EDGE; val cy = y - dy + Sprite.EDGE
            if (cx in 0 until c.w && cy in 0 until c.h && c.px[cy * c.w + cx] != CLEAR) px[y * w + x] = c.px[cy * c.w + cx]
        }
        fun bar(x: Int, y: Int) {
            if (x !in 0 until w || y !in 0 until h) return
            val k = y * w + x
            px[k] = if (px[k] == INK || px[k] == PAPER) INK else LINE
        }
        for (b in bars) for (y in from until to) { bar(b, y); bar(b + 1, y) }
        for (r in rails) for (x in bars.first() until bars.last() + 2) { bar(x, r); bar(x, r + 1) }
        return Sprite(w, h, px)
    }

